// Node tests for the diagram <-> generated-code traceability (src/trace.ts —
// docs/08 R20): the owner of a file, the identifier pattern of an element, the
// lines it lights in an aggregate file, the CodeLens targets and the report.
// The fixtures are the manifest and the env of the yapp_buffer tutorial bench,
// as quick-uvm 1.1.0 emits them.
//   npm run test:trace
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import esbuild from "esbuild";

const outDir = mkdtempSync(join(tmpdir(), "quickuvm-trace-"));
const outFile = join(outDir, "trace.mjs");
await esbuild.build({
  entryPoints: ["src/trace.ts"],
  outfile: outFile,
  bundle: true,
  format: "esm",
  platform: "node",
  logLevel: "silent",
});
const { ownerOfFile, ownerLabel, tracePattern, traceLines, traceLenses, traceReport, isInferred } =
  await import(pathToFileURL(outFile));

let passed = 0;
function test(name, fn) {
  fn();
  passed += 1;
  console.log(`  ok ${name}`);
}

