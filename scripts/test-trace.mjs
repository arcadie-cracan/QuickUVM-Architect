test("ownerOfFile: by basename, on any path shape; unknown files are null", () => {
  assert.equal(ownerOfFile(MANIFEST, "cmd_agent.svh"), "agent:cmd");
  assert.equal(ownerOfFile(MANIFEST, "/w/tb/cmd_driver.svh"), "agent:cmd");
  assert.equal(ownerOfFile(MANIFEST, "C:\\w\\tb\\yapp_buffer_scoreboard.svh"), "scoreboard:pkt_sb");
  assert.equal(ownerOfFile(MANIFEST, "yapp_buffer_env.svh"), "aggregate");
  assert.equal(ownerOfFile(MANIFEST, "yapp_buffer_test.svh"), "test:yapp_buffer_test");
  assert.equal(ownerOfFile(MANIFEST, "user_notes.svh"), null);
  assert.equal(ownerOfFile(MANIFEST, "yapp_buffer.sv"), "aggregate", "the DUT stub is an aggregate file");
});

test("ownerLabel: the kinds read as the diagram names them", () => {
  assert.equal(ownerLabel("agent:cmd"), "agent cmd");
  assert.equal(ownerLabel("scoreboard:pkt_sb"), "scoreboard pkt_sb");
  assert.equal(ownerLabel("vseq:x"), "virtual sequence x");
  assert.equal(ownerLabel("probes"), "probes");
  assert.equal(ownerLabel("aggregate"), "whole-config files");
});

test("tracePattern + traceLines: an agent lights its handles, cfg, coverage and sequencer lines in the env", () => {
  const p = tracePattern(MANIFEST, "agent:cmd");
  assert.ok(p instanceof RegExp);
  assert.deepEqual(traceLines(ENV, p), [9, 19, 22, 23, 27, 31, 33, 34]);
  // the other agent's lines are not lit, nor the comment lines
  const r = tracePattern(MANIFEST, "agent:rsp");
  assert.deepEqual(traceLines(ENV, r), [10, 24, 32, 35]);
});

test("tracePattern: a scoreboard lights its handle and its classes (the stems of its files)", () => {
  const p = tracePattern(MANIFEST, "sb:pkt_sb");
  assert.deepEqual(traceLines(ENV, p), [16, 26, 31, 32]);
  assert.deepEqual(traceLines(ENV, tracePattern(MANIFEST, "xsb:pkt_sb")), [16, 26, 31, 32], "a cross-block id maps to the same owner");
  assert.ok(p.test("yapp_buffer_predictor pred;"), "a class from an owned file's stem");
  assert.ok(!p.test("pkt_sbx = 1;"), "word-bounded: pkt_sbx is another identifier");
});

test("tracePattern: coverage, the virtual sequencer and the agent internals", () => {
  assert.deepEqual(traceLines(ENV, tracePattern(MANIFEST, "cov:cmd")), [19, 27, 33]);
  assert.deepEqual(traceLines(ENV, tracePattern(MANIFEST, "vsqr")), [13, 25, 34, 35]);
  assert.deepEqual(traceLines(ENV, tracePattern(MANIFEST, "agent:cmd:u.sequencer")), [34], "cmd_sqr");
  assert.deepEqual(traceLines(ENV, tracePattern(MANIFEST, "agent:cmd:u.driver")), [], "the driver is not mentioned in the env");
});

test("tracePattern: the elements that own no identifier get null", () => {
  for (const id of ["env", "dut", "<if>.cmd", "", "agent:cmd:nope"]) {
    assert.equal(tracePattern(MANIFEST, id), null, id);
  }
});

test("traceLines: the header and the comment lines never match (the file names itself)", () => {
  const vs = "// This File: yapp_buffer_virtual_sequencer.svh\n// vsqr\nclass yapp_buffer_virtual_sequencer extends uvm_sequencer;\n  cmd_sequencer cmd_sqr;\n";
  assert.deepEqual(traceLines(vs, tracePattern(MANIFEST, "vsqr")), [2]);
  assert.deepEqual(traceLines(vs, tracePattern(MANIFEST, "agent:cmd")), [3]);
});

test("traceLenses: an owned file gets one lens at its top, an aggregate one per element at its first line", () => {
  assert.deepEqual(traceLenses(MANIFEST, "cmd_driver.svh", "class cmd_driver;", null), [
    { line: 0, nodeId: "agent:cmd", owner: "agent:cmd", label: "agent cmd", inferred: false },
  ]);
  const env = traceLenses(MANIFEST, "/w/tb/yapp_buffer_env.svh", ENV, null);
  assert.deepEqual(
    env.map((l) => [l.line, l.nodeId]),
    [
      [9, "agent:cmd"],
      [10, "agent:rsp"],
      [13, "vsqr"],
      [16, "sb:pkt_sb"],
      [19, "cov:cmd"],
    ],
    "sorted by line; the test owner has no node; the coverage collector is a node of its own"
  );
  assert.deepEqual(traceLenses(MANIFEST, "yapp_buffer_test.svh", "class yapp_buffer_test;", null), [], "tests are not drawn");
  assert.deepEqual(traceLenses(MANIFEST, "notes.svh", "x", null), []);
});

test("traceLenses + isInferred: the implicit scoreboard and vseq are flagged from resolve", () => {
  assert.equal(isInferred(RESOLVED_IMPLICIT, "scoreboard:sbd"), true);
  assert.equal(isInferred(RESOLVED_IMPLICIT, "vseq:yapp_buffer_vseq"), true);
  assert.equal(isInferred(RESOLVED_IMPLICIT, "agent:cmd"), false);
  assert.equal(isInferred(null, "scoreboard:sbd"), false, "no resolve: nothing is claimed inferred");
  const sb = traceLenses(IMPLICIT, "yapp_buffer_scoreboard.svh", "class yapp_buffer_scoreboard;", RESOLVED_IMPLICIT);
  assert.deepEqual(sb, [{ line: 0, nodeId: "sb:sbd", owner: "scoreboard:sbd", label: "scoreboard sbd", inferred: true }]);
});

test("traceReport: declared / inferred / aggregate sections, with the on-disk flags", () => {
  const present = new Set(["cmd_agent.svh", "cmd_if.sv"]);
  const md = traceReport(IMPLICIT, RESOLVED_IMPLICIT, present, "yapp_buffer.quickuvm.yaml");
  assert.match(md, /^# Traceability — yapp_buffer\.quickuvm\.yaml/);
  assert.match(md, /\| agent cmd \| .*✓ `cmd_agent\.svh`/);
  assert.match(md, /○ `cmd_driver\.svh`/);
  assert.match(md, /## Inferred by quick-uvm[\s\S]*implicit mode[\s\S]*\| scoreboard sbd \|/);
  assert.match(md, /\| virtual sequence yapp_buffer_vseq \|/);
  assert.ok(md.indexOf("| scoreboard sbd |") > md.indexOf("## Inferred"), "the inferred rows are under their heading");
  assert.ok(md.indexOf("| agent cmd |") < md.indexOf("## Inferred"), "the declared rows are above it");
  assert.match(md, /## Whole-config files[\s\S]*`tb_top\.sv`/);
  const none = traceReport(MANIFEST, null, null, "x.yaml");
  assert.match(none, /## Inferred by quick-uvm[^\n]*\n\nNone\./);
  assert.ok(!none.includes("✓"), "no flags when the disk state is unknown");
});

test("review: a name that prefixes another element's does not light the other's lines", () => {
  // agents `cmd` and `cmd_rsp` (a shared bus prefix is ordinary: axi / axi_lite)
  const m = {
    ...MANIFEST,
    elements: [
      ...MANIFEST.elements,
      { owner: "agent:cmd_rsp", files: files("cmd_rsp_if.sv", "cmd_rsp_cfg.svh", "cmd_rsp_agent.svh", "cmd_rsp_cov.svh") },
    ],
  };
  const env = [
    "  cmd_agent  cmd_agnt;", // 0
    "  cmd_rsp_agent  cmd_rsp_agnt;", // 1
    '    uvm_config_db#(cmd_rsp_cfg)::set(this, "cmd_rsp_agnt", "cfg", env_cfg.cmd_rsp_cfg);', // 2
    "    vsqr.cmd_rsp_sqr = cmd_rsp_agnt.sqr;", // 3
    "    vsqr.cmd_sqr = cmd_agnt.sqr;", // 4
  ].join("\n");
  assert.deepEqual(traceLines(env, tracePattern(m, "agent:cmd")), [0, 4]);
  assert.deepEqual(traceLines(env, tracePattern(m, "agent:cmd_rsp")), [1, 2, 3]);
});

test("review: an agent named with the DUT's prefix does not light the whole env", () => {
  // agent `yapp` on DUT `yapp_buffer`: `yapp_buffer_env`, `_scoreboard`, `_vseq` are not its
  const m = {
    ...MANIFEST,
    elements: [
      ...MANIFEST.elements,
      { owner: "agent:yapp", files: files("yapp_if.sv", "yapp_cfg.svh", "yapp_agent.svh", "yapp_cov.svh") },
    ],
  };
  const env = [
    "class yapp_buffer_env extends uvm_env;", // 0
    "  yapp_agent  yapp_agnt;", // 1
    "  yapp_buffer_virtual_sequencer vsqr;", // 2
    "  yapp_buffer_scoreboard pkt_sb;", // 3
    '    uvm_config_db#(yapp_cfg)::set(this, "yapp_agnt", "cfg", env_cfg.yapp_cfg);', // 4
    "  yapp_buffer dut_inst (.clk(clk));", // 5
    "  yapp_buffer_env_cfg env_cfg;", // 6
  ].join("\n");
  assert.deepEqual(traceLines(env, tracePattern(m, "agent:yapp")), [1, 4]);
  const lens = traceLenses(m, "yapp_buffer_env.svh", env, null).find((l) => l.nodeId === "agent:yapp");
  assert.equal(lens?.line, 1, "the lens lands on the agent's handle, not on the env class");
});

test("review: an ordinal scoreboard id (`sb:x#2`) traces the entry's name", () => {
  assert.deepEqual(traceLines(ENV, tracePattern(MANIFEST, "sb:pkt_sb#2")), [16, 26, 31, 32]);
});

test("review: the coverage collector is a node of its own — its file's lens and the aggregate lens", () => {
  assert.deepEqual(traceLenses(MANIFEST, "cmd_cov.svh", "class cmd_cov;", null), [
    { line: 0, nodeId: "cov:cmd", owner: "agent:cmd", label: "coverage on cmd", inferred: false },
  ]);
  const inferred = traceLenses(IMPLICIT, "cmd_cov.svh", "class cmd_cov;", RESOLVED_IMPLICIT);
  assert.equal(inferred[0].inferred, true, "implicit mode: the generator's coverage");
  const env = traceLenses(MANIFEST, "yapp_buffer_env.svh", ENV, null);
  assert.deepEqual(
    env.map((l) => [l.line, l.nodeId]),
    [
      [9, "agent:cmd"],
      [10, "agent:rsp"],
      [13, "vsqr"],
      [16, "sb:pkt_sb"],
      [19, "cov:cmd"],
    ],
    "rsp has a cov file but the env never mentions rsp_cov: no lens for it"
  );
});

test("review: the report lists the inferred coverage collector among the untraceable", () => {
  const md = traceReport(IMPLICIT, RESOLVED_IMPLICIT, new Set(["cmd_cov.svh"]), "x.yaml");
  assert.match(md, /## Inferred by quick-uvm[\s\S]*\| coverage on cmd \| ✓ `cmd_cov\.svh` \(emitted under agent cmd\) \|/);
  const declared = traceReport(MANIFEST, { ...RESOLVED_IMPLICIT, analysis: { mode: "declared", scoreboards: [], coverage: [{ agent: "cmd", origin: "declared" }] } }, null, "x.yaml");
  assert.ok(!declared.includes("coverage on cmd"), "a declared collector is the agent's row");
});

